"""Safe project-local KiCad symbol-library generation for reviewed LCSC passives."""

from __future__ import annotations

import copy
import json
import os
import re
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import TypeAlias


@dataclass(frozen=True, slots=True)
class Atom:
    value: str


@dataclass(frozen=True, slots=True)
class Quoted:
    value: str


Sexp: TypeAlias = Atom | Quoted | list["Sexp"]
_GENERATOR = "kicad_jlcpcb_interface"
_LIBRARY_BASENAME = "JLCPCB_Generated"
_LIBRARY_DESCRIPTION = "Project-local passive symbols generated from reviewed LCSC data"
_TOKEN = re.compile(r'\s+|;[^\r\n]*(?:\r?\n|$)|"(?:\\.|[^"\\])*"|[()]|[^\s()"]+')
_RESERVED_PROPERTIES = {
    "reference", "value", "footprint", "datasheet", "description",
    "ki_keywords", "ki_description", "ki_locked", "ki_fp_filters",
    "jlcpcb generated by",
}
_RESERVED_NORMALIZED = {
    re.sub(r"[^a-z0-9]", "", name.casefold())
    for name in _RESERVED_PROPERTIES
}


class SymbolLibraryError(RuntimeError):
    """A safe project-local library operation could not be completed."""


class SymbolLibraryConflict(SymbolLibraryError):
    """A library, symbol, or table entry exists but is not safely replaceable."""


@dataclass(frozen=True, slots=True)
class GeneratedLibrarySymbol:
    project_directory: Path
    nickname: str
    symbol_name: str
    library_id: str
    library_path: Path
    table_path: Path
    created: bool
    already_present: bool


def parse_sexpr(text: str) -> Sexp:
    """Parse one KiCad S-expression document without losing quoted/bare tokens."""
    tokens: list[Sexp | str] = []
    for match in _TOKEN.finditer(str(text).lstrip("\ufeff")):
        raw = match.group(0)
        if not raw or raw.isspace() or raw.startswith(";"):
            continue
        if raw in ("(", ")"):
            tokens.append(raw)
        elif raw.startswith('"'):
            try:
                value = json.loads(raw)
            except json.JSONDecodeError as exc:
                raise SymbolLibraryError(
                    f"Invalid quoted S-expression string at offset {match.start()}."
                ) from exc
            if not isinstance(value, str):
                raise SymbolLibraryError("A quoted S-expression token was not a string.")
            tokens.append(Quoted(value))
        else:
            tokens.append(Atom(raw))

    position = 0

    def parse_node() -> Sexp:
        nonlocal position
        if position >= len(tokens):
            raise SymbolLibraryError("Unexpected end of S-expression document.")
        token = tokens[position]
        position += 1
        if token == ")":
            raise SymbolLibraryError("Unexpected closing parenthesis in S-expression.")
        if token != "(":
            if isinstance(token, (Atom, Quoted)):
                return token
            raise SymbolLibraryError("Invalid S-expression token.")
        result: list[Sexp] = []
        while position < len(tokens) and tokens[position] != ")":
            result.append(parse_node())
        if position >= len(tokens):
            raise SymbolLibraryError("Unclosed parenthesis in S-expression document.")
        position += 1
        return result

    if not tokens:
        raise SymbolLibraryError("S-expression document is empty.")
    root = parse_node()
    if position != len(tokens):
        raise SymbolLibraryError("S-expression document contains multiple root forms.")
    if not isinstance(root, list):
        raise SymbolLibraryError("S-expression root must be a list.")
    return root


def dump_sexpr(node: Sexp, depth: int = 0) -> str:
    """Serialize a parsed S-expression with stable formatting and safe escaping."""
    if isinstance(node, Atom):
        return node.value
    if isinstance(node, Quoted):
        return json.dumps(node.value, ensure_ascii=False)
    if not isinstance(node, list):
        raise TypeError(f"Unsupported S-expression node: {type(node)!r}")
    if not node:
        return "()"
    if all(isinstance(item, (Atom, Quoted)) for item in node):
        return "(" + " ".join(dump_sexpr(item, depth + 1) for item in node) + ")"
    prefix = dump_sexpr(node[0], depth + 1)
    suffix = "".join(
        "\n" + "  " * (depth + 1) + dump_sexpr(item, depth + 1)
        for item in node[1:]
    )
    return "(" + prefix + suffix + "\n" + "  " * depth + ")"


def _head(node: Sexp) -> str | None:
    if isinstance(node, list) and node and isinstance(node[0], Atom):
        return node[0].value
    return None


def _direct(node: list[Sexp], head: str) -> list[list[Sexp]]:
    return [item for item in node if isinstance(item, list) and _head(item) == head]


def _find_direct(node: list[Sexp], head: str) -> list[Sexp] | None:
    matches = _direct(node, head)
    if len(matches) > 1 and head in {"version", "generator", "id", "effects"}:
        raise SymbolLibraryError(f"Unexpected duplicate ({head} ...) node.")
    return matches[0] if matches else None


def _string_value(node: Sexp | None) -> str:
    return node.value if isinstance(node, (Atom, Quoted)) else ""


def _walk(node: Sexp):
    if isinstance(node, list):
        yield node
        for child in node:
            yield from _walk(child)


def _property(symbol: list[Sexp], name: str) -> list[Sexp] | None:
    matches = [
        item for item in _direct(symbol, "property")
        if len(item) >= 3 and _string_value(item[1]).casefold() == name.casefold()
    ]
    if len(matches) > 1:
        raise SymbolLibraryError(f"Symbol contains duplicate {name!r} properties.")
    return matches[0] if matches else None


def _set_property(symbol: list[Sexp], name: str, value: str) -> None:
    item = _property(symbol, name)
    if item is None or len(item) < 3:
        raise SymbolLibraryError(
            f"The KiCad stock template does not contain its required {name!r} field."
        )
    item[2] = Quoted(str(value))


def _property_id(item: list[Sexp]) -> int | None:
    id_node = _find_direct(item, "id")
    if id_node is None or len(id_node) < 2:
        return None
    try:
        return int(_string_value(id_node[1]))
    except ValueError:
        return None


def _add_hidden_property(
    symbol: list[Sexp], template: list[Sexp], name: str, value: str, field_id: int
) -> None:
    node = copy.deepcopy(template)
    if len(node) < 3:
        raise SymbolLibraryError("The KiCad property template is malformed.")
    node[1] = Quoted(name)
    node[2] = Quoted(value)
    id_node = _find_direct(node, "id")
    if id_node is None:
        node.append([Atom("id"), Atom(str(field_id))])
    elif len(id_node) >= 2:
        id_node[1] = Atom(str(field_id))
    else:
        raise SymbolLibraryError("The KiCad property template has an invalid field ID.")
    effects = _find_direct(node, "effects")
    if effects is None:
        effects = [
            Atom("effects"),
            [Atom("font"), [Atom("size"), Atom("1.27"), Atom("1.27")]],
        ]
        node.append(effects)
    if not any(isinstance(item, Atom) and item.value == "hide" for item in effects[1:]):
        effects.append(Atom("hide"))
    symbol.append(node)


def _symbol_name(kind: str, lcsc: str) -> str:
    prefix = {"resistor": "R", "capacitor": "C"}.get(str(kind).casefold())
    code = re.sub(r"[^A-Za-z0-9_]", "_", str(lcsc).strip().upper())
    if prefix is None or not re.fullmatch(r"C\d{3,}", code):
        raise SymbolLibraryError(
            "Only validated LCSC resistor/capacitor drafts can create library symbols."
        )
    return f"{prefix}_{code}"


def _make_symbol(template: list[Sexp], draft) -> list[Sexp]:
    source_name = _string_value(template[1]) if len(template) > 1 else ""
    name = _symbol_name(draft.kind, draft.lcsc)
    symbol = copy.deepcopy(template)
    if any(_head(child) == "extends" for child in symbol if isinstance(child, list)):
        raise SymbolLibraryError(
            "The stock passive template unexpectedly extends another library symbol."
        )

    for node in _walk(symbol):
        if _head(node) != "symbol" or len(node) < 2:
            continue
        current = _string_value(node[1])
        if current == source_name:
            node[1] = Quoted(name)
        elif current.startswith(source_name + "_"):
            node[1] = Quoted(name + current[len(source_name):])

    pin_count = sum(1 for node in _walk(symbol) if _head(node) == "pin")
    if pin_count != 2:
        raise SymbolLibraryError(
            f"Stock template {source_name!r} has {pin_count} pins; exactly two are required."
        )

    for field_name, field_value in (
        ("Reference", draft.reference_prefix),
        ("Value", draft.value),
        ("Footprint", draft.footprint),
        ("Datasheet", draft.datasheet_url),
        ("Description", draft.description),
    ):
        _set_property(symbol, field_name, field_value)

    template_property = _property(symbol, "Description") or _property(symbol, "Datasheet")
    if template_property is None:
        raise SymbolLibraryError("The stock symbol has no property template for metadata fields.")

    next_id = max(
        (
            value for prop in _direct(symbol, "property")
            if (value := _property_id(prop)) is not None
        ),
        default=4,
    ) + 1
    seen: set[str] = set()
    for field_name, field_value in draft.custom_fields:
        clean_name = str(field_name).strip()
        clean_value = str(field_value).strip()
        normalized = re.sub(r"[^a-z0-9]", "", clean_name.casefold())
        if (
            not clean_name or not clean_value
            or normalized in _RESERVED_NORMALIZED
            or clean_name.casefold().startswith("ki_")
            or len(clean_name) > 64
            or normalized in seen
        ):
            continue
        seen.add(normalized)
        _add_hidden_property(symbol, template_property, clean_name, clean_value, next_id)
        next_id += 1

    _add_hidden_property(
        symbol, template_property, "JLCPCB Generated By", _GENERATOR, next_id
    )
    return symbol


def _root_header(template_root: list[Sexp]) -> list[Sexp]:
    version = _find_direct(template_root, "version")
    if version is None:
        raise SymbolLibraryError("The KiCad Device library has no version node.")
    return [
        Atom("kicad_symbol_lib"),
        copy.deepcopy(version),
        [Atom("generator"), Quoted("kicad_symbol_editor")],
    ]


def _library_is_owned(root: list[Sexp]) -> bool:
    """Recognize only our explicitly marked generated passive symbols."""
    generator = _find_direct(root, "generator")
    if (
        generator is None
        or len(generator) < 2
        or _string_value(generator[1]) != "kicad_symbol_editor"
    ):
        return False
    symbols = _direct(root, "symbol")
    if not symbols:
        return False
    for symbol in symbols:
        if len(symbol) < 2:
            return False
        symbol_name = _string_value(symbol[1])
        lcsc = _symbol_lcsc(symbol)
        reference = _property(symbol, "Reference")
        prefix = (
            _string_value(reference[2])
            if reference is not None and len(reference) >= 3
            else ""
        )
        marker = _property(symbol, "JLCPCB Generated By")
        owner = (
            _string_value(marker[2])
            if marker is not None and len(marker) >= 3
            else ""
        )
        if (
            not lcsc
            or owner != _GENERATOR
            or prefix not in {"R", "C"}
            or symbol_name != f"{prefix}_{lcsc}"
        ):
            return False
    return True


def _root_symbol(root: list[Sexp], name: str) -> list[Sexp] | None:
    matches = [
        item for item in _direct(root, "symbol")
        if len(item) >= 2 and _string_value(item[1]) == name
    ]
    if len(matches) > 1:
        raise SymbolLibraryConflict(f"Library contains duplicate symbol {name!r}.")
    return matches[0] if matches else None


def _symbol_lcsc(symbol: list[Sexp]) -> str:
    item = _property(symbol, "LCSC")
    return _string_value(item[2]) if item is not None and len(item) >= 3 else ""


def _table_entry(table: list[Sexp], nickname: str) -> list[Sexp] | None:
    matches = []
    for item in _direct(table, "lib"):
        name = _find_direct(item, "name")
        if name is not None and len(name) >= 2 and _string_value(name[1]) == nickname:
            matches.append(item)
    if len(matches) > 1:
        raise SymbolLibraryConflict(
            f"The project symbol table contains duplicate {nickname!r} entries."
        )
    return matches[0] if matches else None


def _entry_text(entry: list[Sexp] | None, field: str) -> str:
    node = _find_direct(entry, field) if entry is not None else None
    return _string_value(node[1]) if node is not None and len(node) >= 2 else ""


def _uri_path(project_dir: Path, uri: str) -> Path | None:
    raw = str(uri or "").strip()
    if not raw:
        return None
    raw = raw.replace("${KIPRJMOD}", str(project_dir))
    if "$" + "{" in raw:
        return None
    candidate = Path(raw).expanduser()
    if not candidate.is_absolute():
        candidate = project_dir / candidate
    return candidate.resolve(strict=False)


def _choose_target(project_dir: Path, table: list[Sexp]):
    for suffix in range(100):
        nickname = _LIBRARY_BASENAME if suffix == 0 else f"{_LIBRARY_BASENAME}_{suffix}"
        path = project_dir / f"{nickname}.kicad_sym"
        entry = _table_entry(table, nickname)
        if entry is not None:
            if _entry_text(entry, "type") != "KiCad":
                continue
            if _uri_path(project_dir, _entry_text(entry, "uri")) != path.resolve(strict=False):
                continue
        if path.is_symlink():
            continue
        if path.exists():
            try:
                root = parse_sexpr(path.read_text(encoding="utf-8"))
            except (OSError, SymbolLibraryError, UnicodeError):
                continue
            if not isinstance(root, list) or _head(root) != "kicad_symbol_lib":
                continue
            if not _library_is_owned(root):
                continue
        return nickname, path, entry
    raise SymbolLibraryConflict(
        "Could not allocate a free project-local JLCPCB symbol-library nickname."
    )


def _project_directory(project_or_path) -> Path:
    raw = getattr(project_or_path, "path", project_or_path)
    if raw is None or not str(raw).strip():
        raise SymbolLibraryError(
            "The active KiCad project has no saved path. Save the project before generating a library."
        )
    path = Path(str(raw)).expanduser()
    if path.is_file() or path.suffix.casefold() in {".kicad_pro", ".kicad_sch"}:
        path = path.parent
    path = path.resolve(strict=False)
    if not path.is_dir():
        raise SymbolLibraryError(f"The active project directory does not exist: {path}")
    return path


def find_device_symbol_library(kicad=None, explicit: str | Path | None = None) -> Path:
    """Locate KiCad's installed Device.kicad_sym without depending on a global table."""
    candidates: list[Path] = []
    if explicit is not None:
        candidates.append(Path(explicit).expanduser())
    for key in ("KICAD_SYMBOL_DIR", "KICAD10_SYMBOL_DIR", "KICAD11_SYMBOL_DIR"):
        value = os.environ.get(key, "").strip()
        if value:
            candidates.append(Path(value).expanduser())
    if kicad is not None:
        try:
            candidates.extend(
                Path(value).expanduser()
                for value in kicad.get_paths().values() if value
            )
        except Exception:
            pass
    candidates.extend(
        Path(value)
        for value in (
            "/usr/share/kicad-nightly/symbols",
            "/usr/share/kicad/symbols",
            "/usr/local/share/kicad/symbols",
            "/Applications/KiCad/KiCad.app/Contents/SharedSupport/symbols",
        )
    )
    seen: set[Path] = set()
    for candidate in candidates:
        candidate = candidate.resolve(strict=False)
        if candidate in seen:
            continue
        seen.add(candidate)
        if candidate.is_file() and candidate.name == "Device.kicad_sym":
            return candidate
        for possible in (
            candidate / "Device.kicad_sym",
            candidate / "symbols" / "Device.kicad_sym",
        ):
            if possible.is_file():
                return possible.resolve()
    raise SymbolLibraryError(
        "Could not locate KiCad's Device.kicad_sym. Set KICAD_SYMBOL_DIR to the "
        "folder containing the stock KiCad symbol libraries."
    )


def _load_table(path: Path) -> list[Sexp]:
    if not path.exists():
        return [Atom("sym_lib_table"), [Atom("version"), Atom("7")]]
    if path.is_symlink():
        raise SymbolLibraryConflict("Refusing to modify a symlinked project sym-lib-table.")
    try:
        root = parse_sexpr(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, SymbolLibraryError) as exc:
        raise SymbolLibraryError(f"Could not read project symbol table {path}: {exc}") from exc
    if _head(root) != "sym_lib_table":
        raise SymbolLibraryError(f"Project symbol table {path} has an invalid root node.")
    if _find_direct(root, "version") is None:
        root.insert(1, [Atom("version"), Atom("7")])
    return root


def _atomic_write(path: Path, content: str, *, backup: bool) -> None:
    if path.is_symlink():
        raise SymbolLibraryConflict(f"Refusing to replace symlinked file {path}.")
    if backup and path.exists():
        backup_path = path.with_name(path.name + ".bak")
        suffix = 1
        while backup_path.exists():
            backup_path = path.with_name(path.name + f".bak.{suffix}")
            suffix += 1
        shutil.copy2(path, backup_path)

    fd, tmp_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent)
    )
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            if not content.endswith("\n"):
                handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_path, path)
        try:
            dir_fd = os.open(path.parent, os.O_RDONLY)
            try:
                os.fsync(dir_fd)
            finally:
                os.close(dir_fd)
        except OSError:
            pass
    except Exception:
        tmp_path.unlink(missing_ok=True)
        raise


def generate_project_library_symbol(
    project_or_path, draft, *, device_library: str | Path | None = None, kicad=None
) -> GeneratedLibrarySymbol:
    """Create or reuse a safe project-local symbol cloned from KiCad's stock R/C."""
    project_dir = _project_directory(project_or_path)
    if draft.symbol_hint not in {"Device:R", "Device:C"}:
        raise SymbolLibraryError(
            "Only inferred generic Device:R or Device:C parts can be generated."
        )
    if not draft.value or not draft.footprint:
        raise SymbolLibraryError(
            "A reliable value and reviewed stock footprint are required for symbol generation."
        )
    device_path = find_device_symbol_library(kicad, device_library)
    try:
        device_root = parse_sexpr(device_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, SymbolLibraryError) as exc:
        raise SymbolLibraryError(f"Could not parse KiCad Device library {device_path}: {exc}") from exc
    if _head(device_root) != "kicad_symbol_lib":
        raise SymbolLibraryError("KiCad Device symbol library has an invalid root node.")
    source_name = draft.symbol_hint.split(":", 1)[1]
    stock_symbol = _root_symbol(device_root, source_name)
    if stock_symbol is None:
        raise SymbolLibraryError(
            f"KiCad's Device library does not contain the required {source_name!r} symbol."
        )
    candidate = _make_symbol(stock_symbol, draft)
    symbol_name = _symbol_name(draft.kind, draft.lcsc)

    table_path = project_dir / "sym-lib-table"
    table = _load_table(table_path)
    nickname, library_path, entry = _choose_target(project_dir, table)

    library_existed = library_path.exists()
    if library_existed:
        try:
            library_root = parse_sexpr(library_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, SymbolLibraryError) as exc:
            raise SymbolLibraryConflict(
                f"Could not safely inspect existing generated library {library_path}: {exc}"
            ) from exc
        if _head(library_root) != "kicad_symbol_lib" or not _library_is_owned(library_root):
            raise SymbolLibraryConflict(
                f"Existing file {library_path} is not owned by this generator; it was left untouched."
            )
    else:
        library_root = _root_header(device_root)

    existing_symbol = _root_symbol(library_root, symbol_name)
    already_present = False
    library_changed = False
    if existing_symbol is not None:
        if _symbol_lcsc(existing_symbol) != draft.lcsc:
            raise SymbolLibraryConflict(
                f"Symbol {nickname}:{symbol_name} exists but its LCSC ownership field "
                "does not match. It was not overwritten."
            )
        if dump_sexpr(existing_symbol) != dump_sexpr(candidate):
            raise SymbolLibraryConflict(
                f"Generated symbol {nickname}:{symbol_name} already exists but its content "
                "has changed. It was not overwritten; inspect the existing project symbol."
            )
        already_present = True
    else:
        library_root.append(candidate)
        library_changed = True

    entry_added = entry is None
    if entry_added:
        table.append(
            [
                Atom("lib"),
                [Atom("name"), Quoted(nickname)],
                [Atom("type"), Quoted("KiCad")],
                [Atom("uri"), Quoted("${KIPRJMOD}/" + library_path.name)],
                [Atom("options"), Quoted("")],
                [Atom("descr"), Quoted(_LIBRARY_DESCRIPTION)],
            ]
        )

    if library_changed:
        _atomic_write(library_path, dump_sexpr(library_root), backup=library_existed)
    if entry_added:
        _atomic_write(table_path, dump_sexpr(table), backup=table_path.exists())

    return GeneratedLibrarySymbol(
        project_directory=project_dir,
        nickname=nickname,
        symbol_name=symbol_name,
        library_id=f"{nickname}:{symbol_name}",
        library_path=library_path,
        table_path=table_path,
        created=library_changed,
        already_present=already_present,
    )



def reload_project_symbol_library(kicad, generated: GeneratedLibrarySymbol) -> None:
    """Reload the generated project library in the active Eeschema session."""
    try:
        kicad.reload_library(type=1, scope=2, nicknames=[generated.nickname])
        statuses = kicad.wait_for_libraries(types=[1], scope=2, timeout_s=60.0)
    except Exception as exc:
        raise SymbolLibraryError(
            f"The project library was written, but KiCad could not reload "
            f"{generated.nickname!r}: {exc}. Reopen the project before placing this part."
        ) from exc
    status_items = statuses if isinstance(statuses, (list, tuple)) else ()
    errors = [
        str(item.error_message)
        for item in status_items
        if getattr(item, "nickname", None) == generated.nickname
        and getattr(item, "error_message", None)
    ]
    if errors:
        raise SymbolLibraryError(
            f"KiCad reported an error while loading {generated.nickname!r}: "
            + "; ".join(errors)
        )
