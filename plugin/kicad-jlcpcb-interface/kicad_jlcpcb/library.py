from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True, slots=True)
class Atom:
    value: str


@dataclass(frozen=True, slots=True)
class Quoted:
    value: str


type Sexp = Atom | Quoted | list["Sexp"]
_GENERATOR = "kicad_jlcpcb_interface"
_LIBRARY_BASENAME = "JLCPCB_Generated"
_LIBRARY_DESCRIPTION = "Project-local JLCPCB symbols copied from reviewed KiCad library templates"
_TOKEN = re.compile(r'\s+|;[^\r\n]*(?:\r?\n|$)|"(?:\\.|[^"\\])*"|[()]|[^\s()"]+')
_RESERVED_PROPERTIES = {
    "reference", "value", "footprint", "datasheet", "description",
    "ki_keywords", "ki_description", "ki_locked", "ki_fp_filters",
    "jlcpcb generated by",
}
_RESERVED_NORMALIZED = {
    re.sub(r"[^a-z0-9]", "", name.casefold())
    for name in _RESERVED_PROPERTIES
}


@dataclass(frozen=True, slots=True)
class GeneratedLibraryFootprint:
    project_directory: Path
    nickname: str
    footprint_name: str
    footprint_id: str
    library_path: Path
    table_path: Path
    created: bool
    already_present: bool


class SymbolLibraryError(RuntimeError):
    """A safe project-local library operation could not be completed."""


class SymbolLibraryConflict(SymbolLibraryError):
    """A library, symbol, or table entry exists but is not safely replaceable."""


@dataclass(frozen=True, slots=True)
class GeneratedLibrarySymbol:
    project_directory: Path
    nickname: str
    symbol_name: str
    library_id: str
    library_path: Path
    table_path: Path
    created: bool
    already_present: bool
    reference_prefix: str = "U"


def parse_sexpr(text: str) -> Sexp:
    """Parse one KiCad S-expression document without losing quoted/bare tokens."""
    tokens: list[Sexp | str] = []
    for match in _TOKEN.finditer(str(text).lstrip("\ufeff")):
        raw = match.group(0)
        if not raw or raw.isspace() or raw.startswith(";"):
            continue
        if raw in ("(", ")"):
            tokens.append(raw)
        elif raw.startswith('"'):
            try:
                value = json.loads(raw)
            except json.JSONDecodeError as exc:
                raise SymbolLibraryError(
                    f"Invalid quoted S-expression string at offset {match.start()}."
                ) from exc
            if not isinstance(value, str):
                raise SymbolLibraryError("A quoted S-expression token was not a string.")
            tokens.append(Quoted(value))
        else:
            tokens.append(Atom(raw))

    position = 0

    def parse_node() -> Sexp:
        nonlocal position
        if position >= len(tokens):
            raise SymbolLibraryError("Unexpected end of S-expression document.")
        token = tokens[position]
        position += 1
        if token == ")":
            raise SymbolLibraryError("Unexpected closing parenthesis in S-expression.")
        if token != "(":
            if isinstance(token, (Atom, Quoted)):
                return token
            raise SymbolLibraryError("Invalid S-expression token.")
        result: list[Sexp] = []
        while position < len(tokens) and tokens[position] != ")":
            result.append(parse_node())
        if position >= len(tokens):
            raise SymbolLibraryError("Unclosed parenthesis in S-expression document.")
        position += 1
        return result

    if not tokens:
        raise SymbolLibraryError("S-expression document is empty.")
    root = parse_node()
    if position != len(tokens):
        if tokens[position] == ")":
            raise SymbolLibraryError("Unexpected closing parenthesis in S-expression.")
        raise SymbolLibraryError("S-expression document contains multiple root forms.")
    if not isinstance(root, list):
        raise SymbolLibraryError("S-expression root must be a list.")
    return root


def dump_sexpr(node: Sexp, depth: int = 0) -> str:
    """Serialize a parsed S-expression with stable formatting and safe escaping."""
    if isinstance(node, Atom):
        return node.value
    if isinstance(node, Quoted):
        return json.dumps(node.value, ensure_ascii=False)
    if not isinstance(node, list):
        raise TypeError(f"Unsupported S-expression node: {type(node)!r}")
    if not node:
        return "()"
    if all(isinstance(item, (Atom, Quoted)) for item in node):
        return "(" + " ".join(dump_sexpr(item, depth + 1) for item in node) + ")"
    prefix = dump_sexpr(node[0], depth + 1)
    suffix = "".join(
        "\n" + "  " * (depth + 1) + dump_sexpr(item, depth + 1)
        for item in node[1:]
    )
    return "(" + prefix + suffix + "\n" + "  " * depth + ")"


def _head(node: Sexp) -> str | None:
    if isinstance(node, list) and node and isinstance(node[0], Atom):
        return node[0].value
    return None


def _direct(node: list[Sexp], head: str) -> list[list[Sexp]]:
    return [item for item in node if isinstance(item, list) and _head(item) == head]


def _find_direct(node: list[Sexp], head: str) -> list[Sexp] | None:
    matches = _direct(node, head)
    if len(matches) > 1 and head in {"version", "generator", "id", "effects"}:
        raise SymbolLibraryError(f"Unexpected duplicate ({head} ...) node.")
    return matches[0] if matches else None


def _string_value(node: Sexp | None) -> str:
    return node.value if isinstance(node, (Atom, Quoted)) else ""


def _walk(node: Sexp):
    if isinstance(node, list):
        yield node
        for child in node:
            yield from _walk(child)


def _property(symbol: list[Sexp], name: str) -> list[Sexp] | None:
    matches = [
        item for item in _direct(symbol, "property")
        if len(item) >= 3 and _string_value(item[1]).casefold() == name.casefold()
    ]
    if len(matches) > 1:
        raise SymbolLibraryError(f"Symbol contains duplicate {name!r} properties.")
    return matches[0] if matches else None


def _set_property(symbol: list[Sexp], name: str, value: str) -> None:
    item = _property(symbol, name)
    if item is None or len(item) < 3:
        raise SymbolLibraryError(
            f"The KiCad stock template does not contain its required {name!r} field."
        )
    item[2] = Quoted(str(value))


def _property_id(item: list[Sexp]) -> int | None:
    id_node = _find_direct(item, "id")
    if id_node is None or len(id_node) < 2:
        return None
    try:
        return int(_string_value(id_node[1]))
    except ValueError:
        return None


def _add_hidden_property(
    symbol: list[Sexp], template: list[Sexp], name: str, value: str, field_id: int
) -> None:
    node = copy.deepcopy(template)
    if len(node) < 3:
        raise SymbolLibraryError("The KiCad property template is malformed.")
    node[1] = Quoted(name)
    node[2] = Quoted(value)
    id_node = _find_direct(node, "id")
    if id_node is None:
        node.append([Atom("id"), Atom(str(field_id))])
    elif len(id_node) >= 2:
        id_node[1] = Atom(str(field_id))
    else:
        raise SymbolLibraryError("The KiCad property template has an invalid field ID.")
    effects = _find_direct(node, "effects")
    if effects is None:
        effects = [
            Atom("effects"),
            [Atom("font"), [Atom("size"), Atom("1.27"), Atom("1.27")]],
        ]
        node.append(effects)
    if not any(isinstance(item, Atom) and item.value == "hide" for item in effects[1:]):
        effects.append(Atom("hide"))
    symbol.append(node)


def _symbol_name(kind: str, lcsc: str, reference_prefix: str = "") -> str:
    prefix = str(
        reference_prefix or {"resistor": "R", "capacitor": "C", "inductor": "L",
                             "diode": "D", "led": "D", "fuse": "F", "crystal": "Y"}.get(
                                 str(kind).casefold(), "U"
                             )
    ).strip().upper()
    code = str(lcsc or "").strip().upper()
    if not re.fullmatch(r"[A-Z][A-Z0-9]{0,7}", prefix):
        raise SymbolLibraryError(
            "The symbol reference prefix must be a short KiCad prefix such as R, D or U."
        )
    if not re.fullmatch(r"C\d{3,}", code):
        raise SymbolLibraryError(
            "A validated LCSC part number is required to create a project symbol."
        )
    return f"{prefix}_{code}"


def _make_symbol(template: list[Sexp], draft) -> list[Sexp]:
    source_name = _string_value(template[1]) if len(template) > 1 else ""
    reference_property = _property(template, "Reference")
    source_prefix = (
        _string_value(reference_property[2])
        if reference_property is not None and len(reference_property) >= 3
        else ""
    )
    reference_prefix = str(draft.reference_prefix or source_prefix or "U").strip().upper()
    name = _symbol_name(draft.kind, draft.lcsc, reference_prefix)
    symbol = copy.deepcopy(template)
    if any(_head(child) == "extends" for child in symbol if isinstance(child, list)):
        raise SymbolLibraryError(
            "The selected stock symbol extends another symbol. Choose a standalone symbol "
            "so the project-local copy preserves its complete definition."
        )

    for node in _walk(symbol):
        if _head(node) != "symbol" or len(node) < 2:
            continue
        current = _string_value(node[1])
        if current == source_name:
            node[1] = Quoted(name)
        elif current.startswith(source_name + "_"):
            node[1] = Quoted(name + current[len(source_name):])

    pin_count = sum(1 for node in _walk(symbol) if _head(node) == "pin")
    if pin_count < 1:
        raise SymbolLibraryError(
            f"Selected stock symbol {source_name!r} has no pins; choose a component symbol."
        )

    for field_name, field_value in (
        ("Reference", reference_prefix),
        ("Value", draft.value),
        ("Footprint", draft.footprint),
        ("Datasheet", draft.datasheet_url),
        ("Description", draft.description),
    ):
        if field_name == "Description" and _property(symbol, field_name) is None:
            continue
        _set_property(symbol, field_name, field_value)

    template_property = _property(symbol, "Description") or _property(symbol, "Datasheet")
    if template_property is None:
        raise SymbolLibraryError("The stock symbol has no property template for metadata fields.")

    next_id = max(
        (
            value for prop in _direct(symbol, "property")
            if (value := _property_id(prop)) is not None
        ),
        default=4,
    ) + 1
    seen: set[str] = set()
    for field_name, field_value in draft.custom_fields:
        clean_name = str(field_name).strip()
        clean_value = str(field_value).strip()
        normalized = re.sub(r"[^a-z0-9]", "", clean_name.casefold())
        if (
            not clean_name or not clean_value
            or normalized in _RESERVED_NORMALIZED
            or clean_name.casefold().startswith("ki_")
            or len(clean_name) > 64
            or normalized in seen
        ):
            continue
        seen.add(normalized)
        _add_hidden_property(symbol, template_property, clean_name, clean_value, next_id)
        next_id += 1

    _add_hidden_property(
        symbol, template_property, "JLCPCB Generated By", _GENERATOR, next_id
    )
    return symbol


def _root_header(template_root: list[Sexp]) -> list[Sexp]:
    version = _find_direct(template_root, "version")
    if version is None:
        raise SymbolLibraryError("The source KiCad symbol library has no version node.")
    return [
        Atom("kicad_symbol_lib"),
        copy.deepcopy(version),
        [Atom("generator"), Quoted("kicad_symbol_editor")],
    ]


def _library_is_owned(root: list[Sexp]) -> bool:
    """Recognize only our explicitly marked generated JLCPCB symbols."""
    generator = _find_direct(root, "generator")
    if (
        generator is None
        or len(generator) < 2
        or _string_value(generator[1]) != "kicad_symbol_editor"
    ):
        return False
    symbols = _direct(root, "symbol")
    if not symbols:
        return False
    for symbol in symbols:
        if len(symbol) < 2:
            return False
        symbol_name = _string_value(symbol[1])
        lcsc = _symbol_lcsc(symbol)
        reference = _property(symbol, "Reference")
        prefix = (
            _string_value(reference[2])
            if reference is not None and len(reference) >= 3
            else ""
        )
        marker = _property(symbol, "JLCPCB Generated By")
        owner = (
            _string_value(marker[2])
            if marker is not None and len(marker) >= 3
            else ""
        )
        if (
            not lcsc
            or owner != _GENERATOR
            or not re.fullmatch(r"[A-Z][A-Z0-9]{0,7}", prefix)
            or symbol_name != f"{prefix}_{lcsc}"
        ):
            return False
    return True


def _root_symbol(root: list[Sexp], name: str) -> list[Sexp] | None:
    matches = [
        item for item in _direct(root, "symbol")
        if len(item) >= 2 and _string_value(item[1]) == name
    ]
    if len(matches) > 1:
        raise SymbolLibraryConflict(f"Library contains duplicate symbol {name!r}.")
    return matches[0] if matches else None


def _symbol_lcsc(symbol: list[Sexp]) -> str:
    item = _property(symbol, "LCSC")
    return _string_value(item[2]) if item is not None and len(item) >= 3 else ""


def _table_entry(table: list[Sexp], nickname: str) -> list[Sexp] | None:
    matches = []
    for item in _direct(table, "lib"):
        name = _find_direct(item, "name")
        if name is not None and len(name) >= 2 and _string_value(name[1]) == nickname:
            matches.append(item)
    if len(matches) > 1:
        raise SymbolLibraryConflict(
            f"The project symbol table contains duplicate {nickname!r} entries."
        )
    return matches[0] if matches else None


def _entry_text(entry: list[Sexp] | None, field: str) -> str:
    node = _find_direct(entry, field) if entry is not None else None
    return _string_value(node[1]) if node is not None and len(node) >= 2 else ""


def _uri_path(project_dir: Path, uri: str) -> Path | None:
    raw = str(uri or "").strip()
    if not raw:
        return None
    raw = raw.replace("${KIPRJMOD}", str(project_dir))
    raw = os.path.expandvars(raw)
    if "$" + "{" in raw:
        return None
    candidate = Path(raw).expanduser()
    if not candidate.is_absolute():
        candidate = project_dir / candidate
    return candidate.resolve(strict=False)


def _choose_target(project_dir: Path, table: list[Sexp]):
    for suffix in range(100):
        nickname = _LIBRARY_BASENAME if suffix == 0 else f"{_LIBRARY_BASENAME}_{suffix}"
        path = project_dir / f"{nickname}.kicad_sym"
        entry = _table_entry(table, nickname)
        if entry is not None:
            if _entry_text(entry, "type") != "KiCad":
                continue
            if _uri_path(project_dir, _entry_text(entry, "uri")) != path.resolve(strict=False):
                continue
        if path.is_symlink():
            continue
        if path.exists():
            try:
                root = parse_sexpr(path.read_text(encoding="utf-8"))
            except (OSError, SymbolLibraryError, UnicodeError):
                continue
            if not isinstance(root, list) or _head(root) != "kicad_symbol_lib":
                continue
            if not _library_is_owned(root):
                continue
        return nickname, path, entry
    raise SymbolLibraryConflict(
        "Could not allocate a free project-local JLCPCB symbol-library nickname."
    )


def _project_directory(project_or_path) -> Path:
    raw = getattr(project_or_path, "path", project_or_path)
    if raw is None or not str(raw).strip():
        raise SymbolLibraryError(
            "The active KiCad project has no saved path. "
            "Save the project before generating a library."
        )
    path = Path(str(raw)).expanduser()
    if path.is_file() or path.suffix.casefold() in {".kicad_pro", ".kicad_sch"}:
        path = path.parent
    path = path.resolve(strict=False)
    if not path.is_dir():
        raise SymbolLibraryError(f"The active project directory does not exist: {path}")
    return path


def find_symbol_library(
    library_nickname: str,
    kicad=None,
    explicit: str | Path | None = None,
    *,
    project_or_path=None,
) -> Path:
    """Locate a named KiCad symbol library in registered tables or stock paths."""
    nickname = str(library_nickname or "").strip()
    if not re.fullmatch(r"[A-Za-z0-9_+-]{1,80}", nickname):
        raise SymbolLibraryError(f"Invalid KiCad symbol-library nickname: {nickname!r}.")
    filename = f"{nickname}.kicad_sym"
    explicit_path = (
        Path(explicit).expanduser().resolve(strict=False)
        if explicit is not None
        else None
    )
    if explicit_path is not None and explicit_path.is_file():
        return explicit_path

    # Project table entries take precedence over globally registered and stock
    # libraries with the same nickname, matching the active KiCad project scope.
    tables: list[tuple[Path, Path]] = []
    if project_or_path is not None:
        project_dir = _project_directory(project_or_path)
        tables.append((project_dir / "sym-lib-table", project_dir))
    tables.extend(
        (path, path.parent) for path in _global_library_tables("sym-lib-table")
    )
    for table_path, base_dir in tables:
        if not table_path.is_file() or table_path.is_symlink():
            continue
        try:
            table = parse_sexpr(table_path.read_text(encoding="utf-8"))
            if _head(table) != "sym_lib_table":
                continue
            entry = _table_entry(table, nickname)
            if entry is None or _entry_text(entry, "type") != "KiCad":
                continue
            library_path = _uri_path(base_dir, _entry_text(entry, "uri"))
            if library_path is not None and library_path.is_file():
                return library_path
        except (OSError, UnicodeError, SymbolLibraryError, ValueError):
            continue

    candidates: list[Path] = []
    if explicit_path is not None:
        candidates.append(explicit_path)
    for key in ("KICAD_SYMBOL_DIR", "KICAD10_SYMBOL_DIR", "KICAD11_SYMBOL_DIR"):
        value = os.environ.get(key, "").strip()
        if value:
            candidates.append(Path(value).expanduser())
    if kicad is not None:
        try:
            candidates.extend(
                Path(value).expanduser()
                for value in kicad.get_paths().values() if value
            )
        except Exception:
            pass
    candidates.extend(
        Path(value)
        for value in (
            "/usr/share/kicad-nightly/symbols",
            "/usr/share/kicad/symbols",
            "/usr/local/share/kicad/symbols",
            "/Applications/KiCad/KiCad.app/Contents/SharedSupport/symbols",
        )
    )
    seen: set[Path] = set()
    for candidate in candidates:
        candidate = candidate.resolve(strict=False)
        if candidate in seen:
            continue
        seen.add(candidate)
        if candidate.is_file() and (candidate.name == filename or candidate == explicit_path):
            return candidate
        for possible in (candidate / filename, candidate / "symbols" / filename):
            if possible.is_file():
                return possible.resolve()

    raise SymbolLibraryError(
        f"Could not locate KiCad's {filename}. Set KICAD_SYMBOL_DIR or register the "
        "library in the active project's or user's sym-lib-table."
    )


def symbol_library_entry_available(
    library_id: str,
    kicad=None,
    project_or_path=None,
) -> bool:
    """Check the active project's resolved Library:Symbol entry."""
    parts = str(library_id or "").strip().split(":", 1)
    if len(parts) != 2 or not all(parts):
        return False

    nickname, symbol_name = parts
    try:
        path = find_symbol_library(
            nickname,
            kicad,
            project_or_path=project_or_path,
        )
        if path.is_symlink() or not path.is_file():
            return False
        root = parse_sexpr(path.read_text(encoding="utf-8"))
        return _head(root) == "kicad_symbol_lib" and _root_symbol(root, symbol_name) is not None
    except (OSError, UnicodeError, SymbolLibraryError, ValueError):
        return False


def _global_library_tables(table_name: str) -> tuple[Path, ...]:
    """Return user-level KiCad library table locations across host platforms."""
    roots = [
        Path.home() / ".config" / "kicad",
        Path.home() / "Library" / "Preferences" / "kicad",
    ]
    appdata = os.environ.get("APPDATA", "").strip()
    if appdata:
        roots.append(Path(appdata) / "kicad")
    tables: set[Path] = set()
    for root in roots:
        if root.is_dir():
            tables.update(root.glob(f"*/{table_name}"))
            direct = root / table_name
            if direct.is_file():
                tables.add(direct)
    return tuple(sorted(tables))




def footprint_library_entry_available(
    footprint_id: str,
    kicad=None,
    project_or_path=None,
) -> bool:
    """Check project/global KiCad tables and stock paths for Library:Footprint."""
    parts = str(footprint_id or "").strip().split(":", 1)
    if len(parts) != 2 or not all(parts):
        return False
    nickname, footprint_name = parts
    if not re.fullmatch(r"[A-Za-z0-9_+-]{1,80}", nickname):
        return False
    if not re.fullmatch(r"[A-Za-z0-9_+.-]{1,120}", footprint_name):
        return False

    tables: list[tuple[Path, Path]] = []
    if project_or_path is not None:
        try:
            project_dir = _project_directory(project_or_path)
            tables.append((project_dir / "fp-lib-table", project_dir))
        except SymbolLibraryError:
            pass
    tables.extend(
        (path, path.parent) for path in _global_library_tables("fp-lib-table")
    )

    for table_path, base_dir in tables:
        if not table_path.is_file() or table_path.is_symlink():
            continue
        try:
            table = parse_sexpr(table_path.read_text(encoding="utf-8"))
            if _head(table) != "fp_lib_table":
                continue
            entry = _table_entry(table, nickname)
            if entry is None or _entry_text(entry, "type") != "KiCad":
                continue
            library_path = _uri_path(base_dir, _entry_text(entry, "uri"))
            if library_path is None or library_path.is_symlink() or not library_path.is_dir():
                continue
            item = library_path / f"{footprint_name}.kicad_mod"
            if item.is_file() and not item.is_symlink():
                return True
        except (OSError, UnicodeError, SymbolLibraryError, ValueError):
            continue

    candidates = []
    for variable in (
        "KICAD_FOOTPRINT_DIR",
        "KICAD8_FOOTPRINT_DIR",
        "KICAD9_FOOTPRINT_DIR",
        "KICAD10_FOOTPRINT_DIR",
        "KICAD11_FOOTPRINT_DIR",
    ):
        value = os.environ.get(variable, "").strip()
        if value:
            candidates.append(Path(value).expanduser())
    candidates.extend(
        Path(value)
        for value in (
            "/usr/share/kicad-nightly/footprints",
            "/usr/share/kicad/footprints",
            "/usr/local/share/kicad/footprints",
            "/Applications/KiCad/KiCad.app/Contents/SharedSupport/footprints",
            "C:/Program Files/KiCad/share/kicad/footprints",
        )
    )
    for root in candidates:
        item = root / f"{nickname}.pretty" / f"{footprint_name}.kicad_mod"
        if item.is_file() and not item.is_symlink():
            return True
    return False


def find_device_symbol_library(kicad=None, explicit: str | Path | None = None) -> Path:
    """Backward-compatible Device library lookup."""
    return find_symbol_library("Device", kicad, explicit)


def _load_table(path: Path) -> list[Sexp]:
    if not path.exists():
        return [Atom("sym_lib_table"), [Atom("version"), Atom("7")]]
    if path.is_symlink():
        raise SymbolLibraryConflict("Refusing to modify a symlinked project sym-lib-table.")
    try:
        root = parse_sexpr(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, SymbolLibraryError) as exc:
        raise SymbolLibraryError(f"Could not read project symbol table {path}: {exc}") from exc
    if _head(root) != "sym_lib_table":
        raise SymbolLibraryError(f"Project symbol table {path} has an invalid root node.")
    if _find_direct(root, "version") is None:
        root.insert(1, [Atom("version"), Atom("7")])
    return root


def _atomic_write(path: Path, content: str, *, backup: bool) -> None:
    if path.is_symlink():
        raise SymbolLibraryConflict(f"Refusing to replace symlinked file {path}.")
    if backup and path.exists():
        backup_path = path.with_name(path.name + ".bak")
        suffix = 1
        while backup_path.exists():
            backup_path = path.with_name(path.name + f".bak.{suffix}")
            suffix += 1
        shutil.copy2(path, backup_path)

    fd, tmp_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent)
    )
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            if not content.endswith("\n"):
                handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_path, path)
        try:
            dir_fd = os.open(path.parent, os.O_RDONLY)
            try:
                os.fsync(dir_fd)
            finally:
                os.close(dir_fd)
        except OSError:
            pass
    except Exception:
        tmp_path.unlink(missing_ok=True)
        raise


def register_project_cad_credits(
    project_or_path,
    source_file: str | Path,
    *,
    lcsc: str,
) -> Path:
    """Copy converter attribution into the project without overwriting user files."""
    project_dir = _project_directory(project_or_path)
    code = str(lcsc or "").strip().upper()
    if not re.fullmatch(r"C\d{3,}", code):
        raise SymbolLibraryError("A validated LCSC number is required for CAD attribution.")
    source_path = Path(source_file).expanduser().resolve(strict=True)
    if not source_path.is_file() or source_path.stat().st_size > 1024 * 1024:
        raise SymbolLibraryError("The CAD attribution file is missing or exceeds 1 MiB.")
    try:
        content = source_path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        raise SymbolLibraryError(f"Could not read CAD attribution: {exc}") from exc
    if not content.strip():
        raise SymbolLibraryError("The CAD converter returned an empty attribution file.")

    target = project_dir / f"JLCPCB_{code}_CREDITS.txt"
    if target.is_symlink():
        raise SymbolLibraryConflict(
            f"Refusing to replace symlinked CAD attribution file {target}."
        )
    if target.exists():
        try:
            existing = target.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            raise SymbolLibraryError(
                f"Could not inspect existing CAD attribution {target}: {exc}"
            ) from exc
        if existing != content:
            raise SymbolLibraryConflict(
                f"Existing CAD attribution file {target.name} differs from the source; "
                "it was left untouched."
            )
        return target

    _atomic_write(target, content, backup=False)
    return target


def generate_project_library_symbol(
    project_or_path, draft, *, device_library: str | Path | None = None, kicad=None
) -> GeneratedLibrarySymbol:
    """Create or reuse a safe project-local copy of a selected KiCad library symbol."""
    project_dir = _project_directory(project_or_path)
    symbol_hint = str(draft.symbol_hint or "").strip()
    if not re.fullmatch(r"[A-Za-z0-9_+-]{1,80}:[A-Za-z0-9_+.-]{1,120}", symbol_hint):
        raise SymbolLibraryError(
            "Choose a KiCad symbol using its Library:Symbol identifier before creating a part."
        )
    if not str(draft.value or "").strip():
        raise SymbolLibraryError(
            "A component value or manufacturer part number is required before placement."
        )
    library_nickname, source_name = symbol_hint.split(":", 1)
    source_path = find_symbol_library(
        library_nickname,
        kicad,
        device_library,
        project_or_path=project_or_path,
    )
    try:
        source_root = parse_sexpr(source_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, SymbolLibraryError) as exc:
        raise SymbolLibraryError(
            f"Could not parse KiCad symbol library {library_nickname} "
            f"at {source_path}: {exc}"
        ) from exc
    if _head(source_root) != "kicad_symbol_lib":
        raise SymbolLibraryError(f"KiCad {library_nickname} library has an invalid root node.")
    stock_symbol = _root_symbol(source_root, source_name)
    if stock_symbol is None:
        raise SymbolLibraryError(
            f"KiCad's {library_nickname} library does not contain {source_name!r}."
        )
    candidate = _make_symbol(stock_symbol, draft)
    reference_property = _property(stock_symbol, "Reference")
    source_prefix = (
        _string_value(reference_property[2])
        if reference_property is not None and len(reference_property) >= 3
        else ""
    )
    reference_prefix = str(draft.reference_prefix or source_prefix or "U").strip().upper()
    symbol_name = _symbol_name(draft.kind, draft.lcsc, reference_prefix)

    table_path = project_dir / "sym-lib-table"
    table = _load_table(table_path)
    nickname, library_path, entry = _choose_target(project_dir, table)

    library_existed = library_path.exists()
    if library_existed:
        try:
            library_root = parse_sexpr(library_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, SymbolLibraryError) as exc:
            raise SymbolLibraryConflict(
                f"Could not safely inspect existing generated library {library_path}: {exc}"
            ) from exc
        if _head(library_root) != "kicad_symbol_lib" or not _library_is_owned(library_root):
            raise SymbolLibraryConflict(
                f"Existing file {library_path} is not owned by this generator; "
                "it was left untouched."
            )
    else:
        library_root = _root_header(source_root)

    existing_symbol = _root_symbol(library_root, symbol_name)
    already_present = False
    library_changed = False
    if existing_symbol is not None:
        if _symbol_lcsc(existing_symbol) != draft.lcsc:
            raise SymbolLibraryConflict(
                f"Symbol {nickname}:{symbol_name} exists but its LCSC ownership field "
                "does not match. It was not overwritten."
            )
        if dump_sexpr(existing_symbol) != dump_sexpr(candidate):
            raise SymbolLibraryConflict(
                f"Generated symbol {nickname}:{symbol_name} already exists but its content "
                "has changed. It was not overwritten; inspect the existing project symbol."
            )
        already_present = True
    else:
        library_root.append(candidate)
        library_changed = True

    entry_added = entry is None
    if entry_added:
        table.append(
            [
                Atom("lib"),
                [Atom("name"), Quoted(nickname)],
                [Atom("type"), Quoted("KiCad")],
                [Atom("uri"), Quoted("${KIPRJMOD}/" + library_path.name)],
                [Atom("options"), Quoted("")],
                [Atom("descr"), Quoted(_LIBRARY_DESCRIPTION)],
            ]
        )

    if library_changed:
        _atomic_write(library_path, dump_sexpr(library_root), backup=library_existed)
    if entry_added:
        _atomic_write(table_path, dump_sexpr(table), backup=table_path.exists())

    return GeneratedLibrarySymbol(
        project_directory=project_dir,
        nickname=nickname,
        symbol_name=symbol_name,
        library_id=f"{nickname}:{symbol_name}",
        library_path=library_path,
        table_path=table_path,
        created=library_changed,
        already_present=already_present,
        reference_prefix=reference_prefix,
    )



def register_project_footprint_library(
    project_or_path,
    source_file: str | Path,
    *,
    lcsc: str,
) -> GeneratedLibraryFootprint:
    """Install one converted footprint in an owned project-local .pretty library.

    A per-LCSC library keeps imported assets isolated. Existing user libraries,
    symlinks and modified imported files are never overwritten.
    """
    project_dir = _project_directory(project_or_path)
    code = str(lcsc or "").strip().upper()
    if not re.fullmatch(r"C\d{3,}", code):
        raise SymbolLibraryError("A validated LCSC number is required for footprint import.")

    source_path = Path(source_file).expanduser().resolve(strict=True)
    if not source_path.is_file() or source_path.suffix.casefold() != ".kicad_mod":
        raise SymbolLibraryError("The EasyEDA converter did not produce a KiCad footprint file.")
    try:
        source_text = source_path.read_text(encoding="utf-8")
        source_root = parse_sexpr(source_text)
    except (OSError, UnicodeError, SymbolLibraryError) as exc:
        raise SymbolLibraryError(f"Could not read the converted footprint: {exc}") from exc
    if _head(source_root) != "footprint" or len(source_root) < 2:
        raise SymbolLibraryError("The converted footprint has an invalid KiCad S-expression root.")
    footprint_name = _string_value(source_root[1]).strip()
    if not re.fullmatch(r"[A-Za-z0-9_+.-]{1,120}", footprint_name):
        raise SymbolLibraryError("The converted footprint has an unsafe KiCad library name.")

    nickname = f"JLCPCB_{code}"
    library_path = project_dir / f"{nickname}.pretty"
    target_path = library_path / f"{footprint_name}.kicad_mod"
    marker_path = library_path / ".jlcpcb-generated.json"
    digest = hashlib.sha256(source_text.encode("utf-8")).hexdigest()
    table_path = project_dir / "fp-lib-table"
    if table_path.is_symlink():
        raise SymbolLibraryConflict("Refusing to modify a symlinked project fp-lib-table.")

    if library_path.is_symlink():
        raise SymbolLibraryConflict(
            f"Refusing to write into symlinked footprint library {library_path}."
        )
    created = False
    already_present = False
    if library_path.exists():
        if not library_path.is_dir() or marker_path.is_symlink() or not marker_path.is_file():
            raise SymbolLibraryConflict(
                f"Existing {library_path.name} is not an owned JLCPCB import; "
                "it was left untouched."
            )
        try:
            marker = json.loads(marker_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            raise SymbolLibraryConflict(
                "The imported footprint ownership marker is unreadable."
            ) from exc
        if marker.get("generator") != _GENERATOR or marker.get("lcsc") != code:
            raise SymbolLibraryConflict(
                "The footprint library ownership marker does not match this part."
            )
        if not target_path.is_file() or target_path.is_symlink():
            raise SymbolLibraryConflict(
                "The owned footprint library is missing its expected footprint."
            )
        try:
            existing_digest = hashlib.sha256(target_path.read_bytes()).hexdigest()
        except OSError as exc:
            raise SymbolLibraryError(f"Could not inspect existing footprint: {exc}") from exc
        if (
            marker.get("footprint") != footprint_name
            or marker.get("sha256") != existing_digest
            or existing_digest != digest
        ):
            raise SymbolLibraryConflict(
                "The imported footprint already exists but has been modified or differs from "
                "the downloaded candidate. It was not overwritten."
            )
        already_present = True
    else:
        staging = Path(tempfile.mkdtemp(prefix=f".{nickname}.", dir=str(project_dir)))
        try:
            staged_pretty = staging / library_path.name
            staged_pretty.mkdir()
            (staged_pretty / target_path.name).write_text(
                source_text, encoding="utf-8", newline="\n"
            )
            marker = {
                "generator": _GENERATOR,
                "lcsc": code,
                "footprint": footprint_name,
                "sha256": digest,
            }
            (staged_pretty / marker_path.name).write_text(
                json.dumps(marker, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
                newline="\n",
            )
            os.replace(staged_pretty, library_path)
            created = True
        except Exception:
            shutil.rmtree(staging, ignore_errors=True)
            raise
        finally:
            shutil.rmtree(staging, ignore_errors=True)

    table = (
        [Atom("fp_lib_table"), [Atom("version"), Atom("7")]]
        if not table_path.exists()
        else None
    )
    if table is None:
        try:
            table = parse_sexpr(table_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, SymbolLibraryError) as exc:
            if created:
                shutil.rmtree(library_path, ignore_errors=True)
            raise SymbolLibraryError(
                f"Could not read project footprint table {table_path}: {exc}"
            ) from exc
        if _head(table) != "fp_lib_table":
            if created:
                shutil.rmtree(library_path, ignore_errors=True)
            raise SymbolLibraryError(
                f"Project footprint table {table_path} has an invalid root node."
            )
        if _find_direct(table, "version") is None:
            table.insert(1, [Atom("version"), Atom("7")])

    entry = _table_entry(table, nickname)
    if entry is not None:
        if (
            _entry_text(entry, "type") != "KiCad"
            or _uri_path(project_dir, _entry_text(entry, "uri"))
            != library_path.resolve(strict=False)
        ):
            if created:
                shutil.rmtree(library_path, ignore_errors=True)
            raise SymbolLibraryConflict(
                f"Footprint library nickname {nickname!r} is already registered to another path."
            )
    else:
        table.append(
            [
                Atom("lib"),
                [Atom("name"), Quoted(nickname)],
                [Atom("type"), Quoted("KiCad")],
                [Atom("uri"), Quoted(f"${{KIPRJMOD}}/{library_path.name}")],
                [Atom("options"), Quoted("")],
                [
                    Atom("descr"),
                    Quoted(
                        f"JLCPCB/EasyEDA import for {code}; review before fabrication"
                    ),
                ],
            ]
        )
        try:
            _atomic_write(table_path, dump_sexpr(table), backup=table_path.exists())
        except Exception:
            if created:
                shutil.rmtree(library_path, ignore_errors=True)
            raise

    return GeneratedLibraryFootprint(
        project_directory=project_dir,
        nickname=nickname,
        footprint_name=footprint_name,
        footprint_id=f"{nickname}:{footprint_name}",
        library_path=library_path,
        table_path=table_path,
        created=created,
        already_present=already_present,
    )


def reload_project_symbol_library(kicad, generated: GeneratedLibrarySymbol) -> None:
    """Reload the generated project library in the active Eeschema session."""
    try:
        kicad.reload_library(type=1, scope=2, nicknames=[generated.nickname])
        statuses = kicad.wait_for_libraries(types=[1], scope=2, timeout_s=60.0)
    except Exception as exc:
        raise SymbolLibraryError(
            f"The project library and table entry were saved, but the active Eeschema "
            f"session could not reload {generated.nickname!r}: {exc}. "
            "No schematic instance was placed. Save and close the project, reopen it, "
            "then run JLCPCB Add or Update Component again with the same LCSC number. "
            "The existing symbol is reused idempotently after KiCad loads the table entry."
        ) from exc
    status_items = statuses if isinstance(statuses, (list, tuple)) else ()
    errors = [
        str(item.error_message)
        for item in status_items
        if getattr(item, "nickname", None) == generated.nickname
        and getattr(item, "error_message", None)
    ]
    if errors:
        raise SymbolLibraryError(
            f"KiCad reported an error while loading {generated.nickname!r}: "
            + "; ".join(errors)
        )
